<?php

namespace App\Services;

use App\Models\Application;
use App\Models\Beneficiary;
use App\Models\Client;
use App\Models\FuneralAssistanceType;
use App\Models\Sex;
use App\Models\User;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Carbon;
use Illuminate\Support\Collection;
use Spatie\Activitylog\Models\Activity;

class RecordExcelExport
{
    public const STATUSES = ['pending', 'assessment', 'processing', 'referred', 'cancelled', 'rejected', 'closed'];

    private const STATUS_RELATIONS = ['currentInterviews', 'workflowStage', 'referral', 'cancellation', 'rejection', 'closure'];

    public function generate(string $report, array $filters, User $user): ?string
    {
        $summary = [
            ($report === 'applications' ? 'Submitted' : 'Recorded').' from' => $filters['from'] ?? 'All',
            'Through' => $filters['until'] ?? 'All', 'Status' => $filters['status'] ?? 'All', 'Barangay' => $filters['barangay'] ?? 'All',
        ];
        if ($report === 'applications') {
            $summary['Assistance type'] = isset($filters['assistance']) ? FuneralAssistanceType::withTrashed()->find($filters['assistance'])?->name : 'All';
        } elseif ($report === 'beneficiaries') {
            $summary['Sex'] = isset($filters['sex']) ? Sex::find($filters['sex'])?->name : 'All';
            $summary['PWD'] = isset($filters['pwd']) ? ($filters['pwd'] ? 'Yes' : 'No') : 'All';
        }
        $history = ! empty($filters['workflow_history']);
        $changes = ! empty($filters['claimant_changes']);
        $book = new RecordWorkbook($report, [
            'Source: '.config('app.name'), 'Generated by: '.$user->fullname(),
            'Generated: '.now('Asia/Manila')->format('Y-m-d H:i:s').' (Asia/Manila)',
            'Filters: '.collect($summary)->map(fn ($v, $k) => "$k: $v")->implode(' | '),
            'History sheets: '.(collect([$history ? 'Workflow History' : null, $changes ? 'Claimant Changes' : null])->filter()->implode(', ') ?: 'None'),
        ]);

        $query = match ($report) {
            'applications' => $this->applications($book, $filters, $history, $changes),
            'clients' => $this->clients($book),
            'beneficiaries' => $this->beneficiaries($book, $filters),
            default => throw new \InvalidArgumentException('Unknown record report.'),
        };
        if (isset($filters['barangay'])) {
            $query->whereHas($report === 'applications' ? 'currentClaimantAssignment.client.address' : 'address', fn ($q) => $q->where('barangay_name', $filters['barangay']));
        }
        if (isset($filters['from'])) {
            $query->whereDate('created_at', '>=', $filters['from']);
        }
        if (isset($filters['until'])) {
            $query->whereDate('created_at', '<=', $filters['until']);
        }

        if ($report === 'applications') {
            foreach ($query->lazyById(100)->chunk(100) as $batch) {
                $applications = $batch->whereInstanceOf(Application::class)
                    ->filter(fn (Application $app) => ! isset($filters['status']) || $app->currentStatus()['label'] === $filters['status']);
                $workers = $this->assessmentWorkers($applications->pluck('assessment.uuid')->filter()->values()->all());
                foreach ($applications as $application) {
                    $this->applicationRow($book, $application, $workers[$application->assessment?->uuid] ?? null);
                    $this->histories($book, $application, $history, $changes);
                }
            }

            return $book->save();
        }

        foreach ($query->lazyById(100) as $record) {
            $application = match (true) {
                $record instanceof Application => $record,
                $record instanceof Client => $record->application ?? $record->claimantAssignments->first()?->application,
                default => $record->application,
            };
            if (! $application) {
                continue;
            }
            $status = $application->currentStatus()['label'];
            if (isset($filters['status']) && $status !== $filters['status']) {
                continue;
            }
            if ($record instanceof Client) {
                $book->row('Clients', [$record->uuid, $record->fullname(), $this->date($record->date_of_birth), $record->demographic?->sex?->name, $record->contact_number, $record->fullAddress(), $record->created_at, $application->tracking_no, $status, $application->client_uuid === $record->uuid ? 'Current' : 'Former']);
            } elseif ($record instanceof Beneficiary) {
                $book->row('Beneficiaries', [$record->uuid, $record->fullname(), $this->date($record->date_of_birth), $this->date($record->date_of_death), $record->date_of_birth && $record->date_of_death ? $record->age() : null, $record->sex?->name, $record->pwd ? 'Yes' : 'No', $record->fullAddress(), $record->created_at, $application->tracking_no, $status]);
            }
        }

        return $book->save();
    }

    private function date(?string $value): ?Carbon
    {
        return $value ? Carbon::parse($value) : null;
    }

    /** @return Builder<Client> */
    private function clients(RecordWorkbook $book): Builder
    {
        $book->table('Clients', ['Record reference', 'Client name', 'Birth date', 'Sex', 'Contact number', 'Address', 'Recorded', 'Application tracking no.', 'Status', 'Claimant designation']);

        return Client::query()->where(fn ($q) => $q->has('application')->orHas('claimantAssignments'))
            ->with(['user', 'address', 'demographic.sex', 'application' => fn ($q) => $q->with(self::STATUS_RELATIONS), 'claimantAssignments.application' => fn ($q) => $q->with(self::STATUS_RELATIONS)]);
    }

    /** @return Builder<Beneficiary> */
    private function beneficiaries(RecordWorkbook $book, array $filters): Builder
    {
        $book->table('Beneficiaries', ['Record reference', 'Beneficiary name', 'Birth date', 'Death date', 'Age at death', 'Sex', 'PWD', 'Address', 'Recorded', 'Application tracking no.', 'Status']);

        return Beneficiary::query()->has('application')->with(['address', 'sex', 'application' => fn ($q) => $q->with(self::STATUS_RELATIONS)])
            ->when(isset($filters['sex']), fn ($q) => $q->where('sex_id', $filters['sex']))
            ->when(isset($filters['pwd']), fn ($q) => $q->where('pwd', $filters['pwd']));
    }

    /** @return Builder<Application> */
    private function applications(RecordWorkbook $book, array $filters, bool $history, bool $changes): Builder
    {
        $book->table('Applications', [
            'Tracking No.', 'Application Date', 'SWA / Worker', 'Current Claimant', 'Beneficiary',
            'Relationship to Beneficiary', 'Beneficiary Date of Birth', 'Age at Death', 'Sex',
            'Claimant Barangay', 'Claimant Address', 'Claimant Contact Number', 'Assistance Type',
            'Recommended Amount', 'Date of Death', 'Application Status',
        ]);
        $query = Application::query()->with([
            ...self::STATUS_RELATIONS, 'assessment', 'beneficiary.sex', 'currentClaimantAssignment.client.user',
            'currentClaimantAssignment.client.address', 'currentClaimantAssignment.relationship',
            'activeRecommendation.funeralAssistanceType' => fn ($q) => $q->withTrashed(),
        ]);
        if ($history) {
            $book->table('Workflow History', ['Tracking no.', 'Cycle', 'Claimant', 'Run reference', 'Workflow / version', 'From stage', 'To stage', 'Date in', 'Date out', 'Processed by', 'Transition reason', 'Custom field values']);
            $query->with(['recommendations.workflow', 'recommendations.claimantAssignment', 'recommendations.workflowHistory.fromStage', 'recommendations.workflowHistory.toStage', 'recommendations.workflowHistory.processedBy', 'recommendations.workflowHistory.customValues' => fn ($q) => $q->whereHas('customField', fn ($field) => $field->whereIn('input_type', ['text', 'number', 'date']))->with('customField')]);
        }
        if ($changes) {
            $book->table('Claimant Changes', ['Tracking no.', 'Previous cycle', 'Previous claimant', 'New cycle', 'New claimant', 'Effective date', 'Recorded by', 'Reason']);
            $query->with('claimantAssignments.assignedBy');
        }

        return $query->when(isset($filters['assistance']), fn ($q) => $q->whereHas('activeRecommendation', fn ($run) => $run->where('funeral_assistance_type_uuid', $filters['assistance'])));
    }

    /**
     * @param  list<string>  $assessmentUuids
     * @return Collection<string, string|null>
     */
    private function assessmentWorkers(array $assessmentUuids): Collection
    {
        if ($assessmentUuids === []) {
            return collect();
        }

        $authorIds = Activity::query()
            ->where('log_name', 'success')
            ->where('description', 'Created assessment')
            ->where('causer_type', (new User)->getMorphClass())
            ->whereNotNull('causer_id')
            ->whereIn('properties->details->assessment_uuid', $assessmentUuids)
            ->get(['properties', 'causer_id'])
            ->groupBy(fn (Activity $activity) => $activity->getProperty('details.assessment_uuid'))
            ->map(function ($entries) {
                $ids = $entries->pluck('causer_id')->unique();

                return $ids->count() === 1 ? $ids->first() : null;
            })
            ->filter();
        $users = User::query()->whereKey($authorIds->values()->all())->get()->keyBy('id');

        return $authorIds->map(fn ($id) => $users->get($id)?->fullname());
    }

    private function applicationRow(RecordWorkbook $book, Application $app, ?string $worker): void
    {
        $assignment = $app->currentClaimantAssignment;
        $client = $assignment?->client;
        $beneficiary = $app->beneficiary;
        $run = $app->activeRecommendation;
        $book->row('Applications', [
            $app->tracking_no,
            $app->created_at,
            $worker,
            $assignment?->identity_snapshot['name'] ?? $client?->fullname(),
            $beneficiary?->fullname(),
            $assignment?->relationship?->name,
            $this->date($beneficiary?->date_of_birth),
            $beneficiary?->date_of_birth && $beneficiary->date_of_death ? $beneficiary->age() : null,
            $beneficiary?->sex?->name,
            $client?->address?->barangay_name,
            $client?->fullAddress(),
            $client?->contact_number,
            $run?->funeralAssistanceType?->name,
            isset($run->amount_extended) ? (float) $run->amount_extended : null,
            $this->date($beneficiary?->date_of_death),
            $app->currentStatus()['label'],
        ]);
    }

    private function histories(RecordWorkbook $book, Application $app, bool $history, bool $changes): void
    {
        if ($history) {
            foreach ($app->recommendations->sortBy([['created_at', 'asc'], ['uuid', 'asc']]) as $run) {
                foreach ($run->workflowHistory->sortBy([['created_at', 'asc'], ['date_in', 'asc'], ['uuid', 'asc']]) as $visit) {
                    $values = $visit->customValues->sortBy('customField.order_no')->map(fn ($v) => $v->customField->label.': '.$v->value)->implode("\n");
                    $book->row('Workflow History', [$app->tracking_no, $run->claimantAssignment?->sequence, $run->claimantAssignment?->identity_snapshot['name'] ?? null, $run->uuid, $run->workflow ? $run->workflow->name.' v'.$run->workflow->version_number : null, $visit->fromStage?->name, $visit->toStage?->name, $this->date($visit->date_in), $this->date($visit->date_out), $visit->processedBy?->fullname(), $visit->reason, $values]);
                }
            }
        }
        if ($changes) {
            $previous = null;
            foreach ($app->claimantAssignments->sortBy('sequence') as $assignment) {
                if ($previous) {
                    $book->row('Claimant Changes', [$app->tracking_no, $previous->sequence, $previous->identity_snapshot['name'] ?? null, $assignment->sequence, $assignment->identity_snapshot['name'] ?? null, $assignment->started_at, $assignment->assignedBy?->fullname(), $assignment->reason]);
                }
                $previous = $assignment;
            }
        }
    }
}
